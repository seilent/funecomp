    private fun list(v: List<String>) = v.ifEmpty { listOf("-") }.joinToString(",")

    private fun line(r: Row, condition: String?) = listOf(
        r.pivot ?: "",
        r.key ?: "",
        Enums.RowKind.names.getValue(r.kind!!),
        r.label ?: "",
        list(r.values),
        list(r.words),
        list(listOfNotNull(r.min, r.max, r.step).map { it.toString() }),
        list(r.flags.map { Enums.RowFlag.names.getValue(it) }),
        condition ?: "-",
    ).joinToString("|")

    @Test
    fun everyBoardSendsItsGoldenRowsWithEveryColumn() {
        for ((b, want) in golden) {
            val d = Device(Options(Board.of(b)), Library.synthetic()) { 0L }
            assertEquals(b, want, d.rows.map { line(it, d.conditionOf(it.key)) })
        }
    }
